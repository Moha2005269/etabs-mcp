"""The ETABS API catalog: every interface, property, method signature and enum.

Built either from the bundled JSON spec (generated by tools/ApiDump from ETABSv1.dll) or, once connected,
live from the loaded assembly via reflection, so the server always validates against the exact ETABS
version it is talking to.
"""

from __future__ import annotations

import difflib
import json
from collections import deque
from collections.abc import Iterable
from dataclasses import dataclass, field
from importlib import resources
from typing import Any

from .errors import ApiNotFoundError

# Entry points an API path may start from. Paths without a root are relative to SapModel.
ROOTS = {"SapModel": "cSapModel", "App": "cOAPI"}
# Interfaces that are not reachable or not meant to be driven through the dispatcher.
HIDDEN_INTERFACES = {"cHelper", "cPluginCallback", "cPluginContract"}
NON_STATUS_PREFIXES = ("Count",)
NUMERIC_TYPES = {"Int16", "Int32", "Int64", "Byte", "UInt16", "UInt32", "UInt64"}
FLOAT_TYPES = {"Double", "Single", "Decimal"}


@dataclass(frozen=True)
class ParamSig:
    name: str
    type: str
    by_ref: bool = False
    is_out: bool = False
    optional: bool = False
    default: str | None = None

    @property
    def is_array(self) -> bool:
        return self.type.endswith("[]")

    @property
    def base_type(self) -> str:
        return self.type[:-2] if self.is_array else self.type


@dataclass(frozen=True)
class MethodSig:
    interface: str
    name: str
    returns: str
    params: tuple[ParamSig, ...]

    @property
    def returns_status(self) -> bool:
        """ETABS convention: Int32 return is a status code (0 = success), except Count* methods."""
        return self.returns == "Int32" and not self.name.startswith(NON_STATUS_PREFIXES)

    @property
    def qualified_name(self) -> str:
        return f"{self.interface}.{self.name}"

    def signature(self) -> str:
        parts = []
        for p in self.params:
            text = ("ref " if p.by_ref else "") + f"{p.type} {p.name}"
            if p.optional:
                text += f" = {p.default!r}" if p.default not in (None, "") else " = <default>"
            parts.append(text)
        return f"{self.returns} {self.name}({', '.join(parts)})"


@dataclass
class InterfaceSig:
    name: str
    properties: dict[str, str] = field(default_factory=dict)
    methods: dict[str, list[MethodSig]] = field(default_factory=dict)
    extends: list[str] = field(default_factory=list)


@dataclass(frozen=True)
class ResolvedPath:
    root: str
    chain: tuple[str, ...]  # property names walked from the root
    interface: str
    methods: tuple[MethodSig, ...]

    @property
    def path(self) -> str:
        return ".".join((self.root, *self.chain, self.methods[0].name))


class ApiCatalog:
    def __init__(
        self,
        interfaces: dict[str, InterfaceSig],
        enums: dict[str, dict[str, int]],
        *,
        source: str,
        version: str | None = None,
    ):
        self.interfaces = interfaces
        self.enums = enums
        self.source = source
        self.version = version
        self._paths = self._compute_interface_paths()

    # ---------------------------------------------------------------- construction

    @classmethod
    def from_spec(cls, spec: dict[str, Any], *, source: str = "bundled") -> ApiCatalog:
        interfaces: dict[str, InterfaceSig] = {}
        for name, entry in spec.get("interfaces", {}).items():
            iface = InterfaceSig(
                name=name,
                properties={p["name"]: p["type"] for p in entry.get("properties", [])},
                extends=list(entry.get("extends", [])),
            )
            for m in entry.get("methods", []):
                sig = MethodSig(
                    interface=name,
                    name=m["name"],
                    returns=m["returns"],
                    params=tuple(
                        ParamSig(
                            name=p["name"],
                            type=p["type"],
                            by_ref=bool(p.get("by_ref")),
                            is_out=bool(p.get("out")),
                            optional=bool(p.get("optional")),
                            default=p.get("default"),
                        )
                        for p in m.get("params", [])
                    ),
                )
                iface.methods.setdefault(sig.name, []).append(sig)
            interfaces[name] = iface
        enums = {k: dict(v) for k, v in spec.get("enums", {}).items()}
        return cls(interfaces, enums, source=source, version=spec.get("file_version"))

    @classmethod
    def load_bundled(cls) -> ApiCatalog:
        text = resources.files("etabs_mcp.data").joinpath("etabs_api_spec.json").read_text(encoding="utf-8")
        return cls.from_spec(json.loads(text), source="bundled ETABSv1.dll spec")

    # ---------------------------------------------------------------- lookups

    def _all_methods(self, iface: str) -> dict[str, list[MethodSig]]:
        out: dict[str, list[MethodSig]] = {}
        stack, seen = [iface], set()
        while stack:
            name = stack.pop()
            if name in seen or name not in self.interfaces:
                continue
            seen.add(name)
            for mname, sigs in self.interfaces[name].methods.items():
                out.setdefault(mname, []).extend(sigs)
            stack.extend(self.interfaces[name].extends)
        return out

    def _compute_interface_paths(self) -> dict[str, tuple[str, tuple[str, ...]]]:
        """Shortest property path from a root to every reachable interface (BFS)."""
        paths: dict[str, tuple[str, tuple[str, ...]]] = {}
        queue: deque[tuple[str, str, tuple[str, ...]]] = deque()
        for root, iface in ROOTS.items():
            if iface in self.interfaces and iface not in paths:
                paths[iface] = (root, ())
                queue.append((iface, root, ()))
        while queue:
            iface, root, chain = queue.popleft()
            for prop, ptype in sorted(self.interfaces[iface].properties.items()):
                if ptype in self.interfaces and ptype not in paths:
                    paths[ptype] = (root, chain + (prop,))
                    queue.append((ptype, root, chain + (prop,)))
        return paths

    def interface_path(self, iface: str) -> str | None:
        if iface not in self._paths:
            return None
        root, chain = self._paths[iface]
        return ".".join((root, *chain))

    def resolve(self, path: str) -> ResolvedPath:
        """Resolve 'FrameObj.GetNameList', 'SapModel.LoadCases.StaticLinear.SetCase', 'App.Hide' or the
        interface-qualified form 'cFrameObj.GetNameList'. Matching is case-insensitive."""
        tokens = [t for t in path.strip().split(".") if t]
        if len(tokens) < 1:
            raise ApiNotFoundError("Empty API path.", hint="Use e.g. 'FrameObj.GetNameList'.")
        method_name = tokens[-1]
        head = tokens[:-1]

        qualified = _ci_key(self.interfaces, head[0]) if len(head) == 1 else None
        if qualified is not None and _ci_key(ROOTS, head[0]) is None:
            iface_name = qualified
            if iface_name not in self._paths:
                raise ApiNotFoundError(f"Interface {iface_name} is not reachable from SapModel or App.")
            root, chain = self._paths[iface_name]
            return self._finish(root, chain, iface_name, method_name, path)

        root = "SapModel"
        if head and _ci_get(ROOTS, head[0]) is not None:
            root = _ci_key(ROOTS, head[0])
            head = head[1:]
        iface_name = ROOTS[root]
        chain: list[str] = []
        for prop in head:
            props = self.interfaces[iface_name].properties
            key = _ci_key(props, prop)
            if key is None:
                raise ApiNotFoundError(
                    f"'{prop}' is not a property of {iface_name} (while resolving '{path}').",
                    hint=_suggest(prop, props.keys(), "Properties"),
                )
            chain.append(key)
            iface_name = props[key]
            if iface_name not in self.interfaces:
                raise ApiNotFoundError(f"Property {key} has non-API type {iface_name}.")
        return self._finish(root, tuple(chain), iface_name, method_name, path)

    def _finish(self, root: str, chain: tuple[str, ...], iface: str, method: str, path: str) -> ResolvedPath:
        methods = self._all_methods(iface)
        key = _ci_key(methods, method)
        if key is None:
            props = self.interfaces[iface].properties
            hint = _suggest(method, list(methods) + list(props), "Members")
            if _ci_key(props, method):
                hint = f"'{method}' is a property (sub-interface), not a method; append a method name to it."
            raise ApiNotFoundError(f"{iface} has no method '{method}' (path '{path}').", hint=hint)
        return ResolvedPath(root=root, chain=chain, interface=iface, methods=tuple(methods[key]))

    # ---------------------------------------------------------------- discovery

    def iter_methods(self) -> Iterable[tuple[str, MethodSig]]:
        for iface in sorted(self.interfaces):
            if iface in HIDDEN_INTERFACES or iface not in self._paths:
                continue
            prefix = self.interface_path(iface)
            for sigs in self.interfaces[iface].methods.values():
                for sig in sigs:
                    yield f"{prefix}.{sig.name}", sig

    def search(self, query: str, *, limit: int = 25, interface: str | None = None) -> list[dict[str, Any]]:
        terms = [t.lower() for t in query.replace(".", " ").split() if t]
        scored = []
        for path, sig in self.iter_methods():
            if interface and sig.interface.lower() != interface.lower():
                continue
            hay_name = path.lower()
            hay_params = " ".join(p.name.lower() for p in sig.params)
            score = 0
            for t in terms:
                if t in sig.name.lower():
                    score += 3
                elif t in hay_name:
                    score += 2
                elif t in hay_params:
                    score += 1
                else:
                    score = -1
                    break
            if score > 0 or not terms:
                scored.append((-score, len(path), path, sig))
        scored.sort(key=lambda s: s[:3])
        return [
            {"path": path, "signature": sig.signature(), "returns_status": sig.returns_status}
            for _, _, path, sig in scored[:limit]
        ]

    def describe(self, path: str) -> dict[str, Any]:
        from .policy import classify  # local import: policy depends on catalog types only

        resolved = self.resolve(path)
        overloads = []
        for sig in resolved.methods:
            params = []
            for p in sig.params:
                entry: dict[str, Any] = {
                    "name": p.name,
                    "type": p.type,
                    "direction": "in/out (returned in outputs)" if p.by_ref else "in",
                    "required": not p.optional and not p.by_ref,
                }
                if p.optional:
                    entry["default"] = p.default
                if p.base_type in self.enums:
                    entry["enum_values"] = self.enums[p.base_type]
                params.append(entry)
            overloads.append(
                {
                    "signature": sig.signature(),
                    "returns": sig.returns,
                    "return_semantics": "status code (0 = success)" if sig.returns_status else "value",
                    "params": params,
                    "safety": classify(sig),
                }
            )
        return {
            "path": resolved.path,
            "interface": resolved.interface,
            "overloads": overloads,
            "notes": (
                "Pass inputs by parameter name in 'args'. ByRef parameters you omit are filled with empty "
                "placeholders and their values come back in 'outputs'. Supply a ByRef parameter only when the "
                "method reads it as input (typical for Set*/Add* methods that take arrays)."
            ),
        }

    def interface_summary(self, iface: str) -> dict[str, Any]:
        key = _ci_key(self.interfaces, iface)
        if key is None:
            raise ApiNotFoundError(f"Unknown interface '{iface}'.", hint=_suggest(iface, self.interfaces, "Interfaces"))
        info = self.interfaces[key]
        return {
            "interface": key,
            "path": self.interface_path(key),
            "properties": info.properties,
            "methods": sorted(self._all_methods(key)),
        }


def _ci_key(mapping: Any, key: str) -> str | None:
    if key in mapping:
        return key
    lowered = key.lower()
    for k in mapping:
        if k.lower() == lowered:
            return k
    return None


def _ci_get(mapping: dict, key: str) -> Any:
    k = _ci_key(mapping, key)
    return mapping[k] if k is not None else None


def _suggest(word: str, options: Iterable[str], label: str) -> str:
    opts = list(options)
    close = difflib.get_close_matches(word, opts, n=5, cutoff=0.5)
    if not close:
        lowered = word.lower()
        close = [o for o in opts if lowered in o.lower()][:5]
    if close:
        return f"Did you mean: {', '.join(close)}?"
    return f"{label}: {', '.join(sorted(opts)[:40])}" + (" ..." if len(opts) > 40 else "")
